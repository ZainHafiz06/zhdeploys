/** A brand mark for a site link; unknown sites fall back to their initial. */
export function SocialIcon({ link }: { link: SiteLink }) {
  const kind = kindOf(link);
  if (!kind) return <span className="social-initial">{link.label.charAt(0).toUpperCase()}</span>;
  return (
    <svg className="social-icon" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
      {PATHS[kind]}
    </svg>
  );
}
